def pic(base, theme, name, alt, attrs='width="100%"'):
    return (f'<picture><source media="(prefers-color-scheme: dark)" srcset="{base}/{theme}/{name}-dark.svg">'
            f'<img alt="{alt}" src="{base}/{theme}/{name}-light.svg" {attrs}></picture>')

def h(base, theme, key, label):
    if theme == "brutal":
        return pic(base, theme, "h-" + key, label)
    return "### " + label


